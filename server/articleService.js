// 封面图生成地址
function coverUrl(prompt) {
  return `https://trae-api-cn.mchost.guru/api/ide/v1/text_to_image?prompt=${encodeURIComponent(prompt)}&image_size=landscape_16_9`;
}

// 获取全部文章
export async function getAllArticles() {
  let articles = await readJSON(ARTICLES_FILE);
  if (!articles.length) {
    articles = await seedArticles();
  }
  return articles;
}

// 分页 + 筛选查询
export async function getArticles({ category, search, page = 1, pageSize = 24 } = {}) {
  let articles = await getAllArticles();
  articles = [...articles].sort((a, b) => new Date(b.created_at) - new Date(a.created_at));

  if (category && category !== 'all') {
    articles = articles.filter(a => String(a.category_id) === String(category));
  }

  if (search) {
    const kw = search.toLowerCase();
    articles = articles.filter(a =>
      (a.title || '').toLowerCase().includes(kw) ||
      (a.summary || '').toLowerCase().includes(kw) ||
      (a.content || '').toLowerCase().includes(kw) ||
      (a.tags || []).some(t => t.toLowerCase().includes(kw))
    );
  }

  const total = articles.length;
  const totalPages = Math.max(1, Math.ceil(total / pageSize));
  const currentPage = Math.min(Math.max(1, page), totalPages);
  const start = (currentPage - 1) * pageSize;
  const items = articles.slice(start, start + pageSize);

  return { items, total, page: currentPage, totalPages };
}

// 按 ID 查询
export async function getArticleById(id) {
  const articles = await getAllArticles();
  return articles.find(a => String(a.id) === String(id)) || null;
}

// 创建文章
export async function createArticle(data) {
  const articles = await getAllArticles();
  const now = new Date().toISOString();
  const article = {
    id: generateId('art'),
    title: (data.title || '').trim(),
    summary: (data.summary || '').trim(),
    content: data.content || '',
    cover_image: data.cover_image || coverUrl('简约抽象插画'),
    category_id: String(data.category_id || '1'),
    author_id: data.author_id || '1',
    views: Number(data.views) || 0,
    tags: Array.isArray(data.tags) ? data.tags : [],
    created_at: data.created_at || now,
    updated_at: now,
  };
  articles.push(article);
  await writeJSON(ARTICLES_FILE, articles);
  return article;
}

// 更新文章
export async function updateArticle(id, updates) {
  const articles = await getAllArticles();
  const idx = articles.findIndex(a => String(a.id) === String(id));
  if (idx === -1) throw new Error('文章不存在');
  articles[idx] = {
    ...articles[idx],
    ...updates,
    id: articles[idx].id,
    updated_at: new Date().toISOString(),
  };
  await writeJSON(ARTICLES_FILE, articles);
  return articles[idx];
}

// 删除文章
export async function deleteArticle(id) {
  const articles = await getAllArticles();
  const idx = articles.findIndex(a => String(a.id) === String(id));
  if (idx === -1) throw new Error('文章不存在');
  const [removed] = articles.splice(idx, 1);
  await writeJSON(ARTICLES_FILE, articles);
  return removed;
}

// ===== 种子数据：每个分类 100 篇真实有意义的文章 =====
async function seedArticles() {
  const articles = [];
  const baseTime = Date.now();

  for (const cat of CATEGORIES) {
    const seed = SEED_DATA[cat.id];
    for (let i = 0; i < 100; i++) {
      const title = seed.titles[i % seed.titles.length];
      const content = seed.contents[i % seed.contents.length];
      const coverPrompt = seed.coverPrompts[i % seed.coverPrompts.length];
      const created = new Date(baseTime - (600 - i) * 3600 * 1000 - Number(cat.id) * 60000).toISOString();
      articles.push({
        id: `art-${cat.id}-${i + 1}`,
        title,
        summary: content.slice(0, 60).replace(/\n/g, ' ') + '…',
        content,
        cover_image: coverUrl(coverPrompt),
        category_id: cat.id,
        author_id: '1',
        views: 100 + Math.floor(Math.random() * 9899),
        tags: seed.tags(i),
        created_at: created,
        updated_at: created,
      });
    }
  }

  await writeJSON(ARTICLES_FILE, articles);
  console.log(`[articleService] 已生成 ${articles.length} 篇种子文章`);
  return articles;
}

